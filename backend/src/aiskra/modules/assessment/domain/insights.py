@dataclass(frozen=True)
class RulesInsights:
    summary: str
    insights: list[str] = field(default_factory=list)
    actions: list[str] = field(default_factory=list)


def rules_insights(
    weakest: list[tuple[str, str, float]],
    errors: list[tuple[str, int]],
    average_score: float,
    passed_share: float,
) -> RulesInsights:
    """`weakest` — (ключ, название, средний балл 0…1) по возрастанию; `errors` — (текст, сколько раз)."""
    weak = [(k, t, a) for k, t, a in weakest if a < 0.8]
    if not weak:
        return RulesInsights(
            summary=(
                f"Средний балл группы {average_score:g}, зачтено {round(passed_share * 100)} %: явных слабых мест нет."
            ),
            actions=["Повысить сложность вызовов или включить психологический модификатор заявителя"],
        )
    key, title, avg = weak[0]
    risk = ADVICE.get(key, ("", ""))[0]
    summary = f"Слабее всего у группы «{title}» — {round(avg * 100)} % от максимума" + (f": {risk}." if risk else ".")
    insights = [
        f"«{t}»: в среднем {round(a * 100)} %" + (f" — {ADVICE[k][0]}" if k in ADVICE else "") for k, t, a in weak[:3]
    ]
    if errors:
        text, n = errors[0]
        insights.append(f"Чаще всего повторяется ошибка «{text}» — {n} раз")
    actions = [ADVICE[k][1][0].upper() + ADVICE[k][1][1:] for k, _, _ in weak[:3] if k in ADVICE]
    return RulesInsights(summary=summary, insights=insights, actions=actions or ["Разобрать частые ошибки на занятии"])
